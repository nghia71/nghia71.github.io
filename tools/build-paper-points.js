#!/usr/bin/env node
// Builds assets/js/paper-points.js: the full marks of each problem on every
// team-test paper. The standings page needs them to tell a perfect score on a
// problem (P k = full marks) from a partial one; the public Exams sheet has
// the scores but not the maxima, and the maxima are NOT the same from paper
// to paper (e.g. L4-C1-A1 is 8,14,14,25,25,14 but L4-C2-A1 is 8,14,25,14,25,14).
//
// Source of truth: the compiled papers, lps67/papers/C<c>/L<l>-C<c>-A<a>.pdf,
// whose problem headers read "Problem n (NN pts)". (The .tex comments are
// not reliable: shared problems take their points from macros.)
// Checks: problems 1..6 each found once, summing to 100.
//
// Needs pdftotext (poppler). Run from the website repo:
//   node tools/build-paper-points.js [path/to/lps67]
// Re-run whenever a new paper is added (new chapter, new retake).
"use strict";
var fs = require("fs"), path = require("path"), cp = require("child_process");
var lps = path.resolve(process.argv[2] || path.join(__dirname, "..", "..", "lps67"));
var papersDir = path.join(lps, "papers");
var out = {}, problems = [];
fs.readdirSync(papersDir).filter(function (d) { return /^C\d+$/.test(d); }).forEach(function (d) {
  fs.readdirSync(path.join(papersDir, d)).forEach(function (f) {
    var m = /^L(\d)-C(\d+)-A(\d)\.tex$/.exec(f);
    if (!m) return;
    var key = m[1] + "-" + m[2] + "-" + m[3];
    var pdf = path.join(papersDir, d, f.replace(/\.tex$/, ".pdf"));
    if (!fs.existsSync(pdf)) { problems.push(key + ": no compiled PDF (not in the table)"); return; }
    var text = cp.execFileSync("pdftotext", ["-layout", pdf, "-"], { encoding: "utf8" });
    var pts = [], dup = false, re = /Problem\s+([1-6])\s*\((\d+)\s*pts\)/g, h;
    while ((h = re.exec(text))) {
      var i = Number(h[1]) - 1;
      if (pts[i] !== undefined && pts[i] !== Number(h[2])) dup = true;
      pts[i] = Number(h[2]);
    }
    var sum = pts.reduce(function (s, x) { return s + (x || 0); }, 0);
    if (dup || pts.length !== 6 || pts.some(function (x) { return !x; }) || sum !== 100) {
      problems.push(key + ": got [" + pts.join(",") + "] sum " + sum + (dup ? " (conflicting headers)" : ""));
      return;
    }
    out[key] = pts;
  });
});
var keys = Object.keys(out).sort(function (a, b) { return a.localeCompare(b, undefined, { numeric: true }); });
var body = keys.map(function (k) { return '  "' + k + '": [' + out[k].join(", ") + "]"; }).join(",\n");
var js = "// GENERATED by tools/build-paper-points.js from the compiled papers in lps67/papers.\n" +
  "// Do not edit by hand. Full marks of problems 1..6 on each team-test paper,\n" +
  "// keyed \"level-chapter-attempt\" (e.g. \"4-2-1\" = L4-C2-A1).\n" +
  "window.MCC_PAPER_POINTS = {\n" + body + "\n};\n";
fs.writeFileSync(path.join(__dirname, "..", "assets", "js", "paper-points.js"), js);
console.log("papers in the table: " + keys.length + "; notes: " + problems.length);
problems.forEach(function (p) { console.log("  " + p); });
